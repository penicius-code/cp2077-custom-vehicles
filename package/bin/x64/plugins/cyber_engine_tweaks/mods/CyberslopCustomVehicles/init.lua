local function log(fmt, ...)
    local s = string.format(fmt, ...)
    spdlog.info(s)
    return s
end

local function note(fmt, ...)
    state.report[#state.report + 1] = log(fmt, ...)
end

local function clamp(v, lo, hi)
    if v < lo then return lo end
    if v > hi then return hi end
    return v
end

local function get(path)
    return TweakDB:GetFlat(path)
end

-- Sets dst flat from src flat (optionally times a factor); false when the source flat does not exist.
local function copyFlat(dstRec, srcRec, prop, factor)
    local v = get(srcRec .. "." .. prop)
    if v == nil then return false end
    if factor ~= nil then v = v * factor end
    TweakDB:SetFlat(dstRec .. "." .. prop, v)
    return true
end

-- ------------------------------------------------------------------ CLONES pass
local function applyClones()
    local done, skipped = 0, 0
    for _, group in ipairs(CLONES) do
        local engine = get(group.base .. ".vehEngineData")
        local driveProp = group.bike and ".bikeDriveModelData" or ".vehDriveModelData"
        local drive = get(group.base .. driveProp)
        if engine == nil or drive == nil then
            note("CLONES %s: base record or its engine / drive model flat is missing, %d targets skipped",
                group.base, #group.targets)
            skipped = skipped + #group.targets
        else
            for _, t in ipairs(group.targets) do
                if get(t .. ".vehEngineData") == nil then
                    note("CLONES %s: target record missing (mod not installed?), skipped", t)
                    skipped = skipped + 1
                else
                    TweakDB:SetFlat(t .. ".vehEngineData", engine)
                    TweakDB:SetFlat(t .. driveProp, drive)
                    done = done + 1
                end
            end
        end
    end
    note("CLONES: %d records now use their base's CVOO engine and drive model, %d skipped", done, skipped)
end

-- ------------------------------------------------------------------ SCALED pass
local function applyScaled(c)
    local T = c.template
    local tEng, tDM = T .. "_full_enginedata", T .. "_full_vehDriveModelData"
    local tFront, tRear = T .. "_full_vehWheelSetupFrontPreset", T .. "_full_vehWheelSetupRearPreset"
    local tTorque = get(tEng .. ".engineMaxTorque")
    local tMass = get(tDM .. ".total_mass")
    local tGears = get(tEng .. ".gears")
    if tTorque == nil or tMass == nil or tGears == nil or #tGears < 2 then
        note("SCALED %s: CVOO records of %s not found, skipped", c.name, T)
        return false
    end

    local main = c.targets[1]
    local ownEng, ownDM = get(main .. ".vehEngineData"), get(main .. ".vehDriveModelData")
    if ownEng == nil or ownDM == nil then
        note("SCALED %s: record %s not found (mod not installed?), skipped", c.name, main)
        return false
    end

    local pre = main .. "_ccv"
    local eng, dm, ws, fr, rr = pre .. "_engine", pre .. "_dm", pre .. "_ws", pre .. "_front", pre .. "_rear"
    TweakDB:CloneRecord(eng, ownEng)
    TweakDB:CloneRecord(dm, ownDM)
    TweakDB:CloneRecord(ws, get(dm .. ".wheelSetup"))
    TweakDB:CloneRecord(fr, get(ws .. ".frontPreset"))
    TweakDB:CloneRecord(rr, get(ws .. ".backPreset"))
    TweakDB:SetFlat(dm .. ".wheelSetup", ws)
    TweakDB:SetFlat(ws .. ".frontPreset", fr)
    TweakDB:SetFlat(ws .. ".backPreset", rr)

    local ownMass = get(dm .. ".total_mass")
    local mr = (ownMass ~= nil and tMass > 0) and (ownMass / tMass) or 1.0
    local r = c.hp / c.hpRef
    local vs = clamp(r ^ (1 / 3), SPEED_SCALE_MIN, SPEED_SCALE_MAX)

    -- engine
    for _, p in ipairs(ENGINE_COPY) do copyFlat(eng, tEng, p) end
    TweakDB:SetFlat(eng .. ".engineMaxTorque", tTorque * r)

    -- gears: gear 0 stays the vehicle's own (reverse), gears 1..n come from the template with speeds scaled
    local ownGears = get(eng .. ".gears")
    local n = #tGears - 1
    local gearNames = {}
    for i = 0, n do
        local g = pre .. "_gear" .. i
        TweakDB:CloneRecord(g, ownGears[1])
        gearNames[#gearNames + 1] = g
    end
    TweakDB:SetFlat(eng .. ".gears", gearNames)
    for i = 1, n do
        local src, dst = T .. "_inline_gear" .. i, pre .. "_gear" .. i
        copyFlat(dst, src, "torqueMultiplier")
        copyFlat(dst, src, "minSpeed", vs)
        copyFlat(dst, src, "maxSpeed", vs)
        copyFlat(dst, src, "minEngineRPM")
        copyFlat(dst, src, "maxEngineRPM")
    end

    -- chassis
    for _, p in ipairs(DRIVE_COPY) do copyFlat(dm, tDM, p) end
    for _, p in ipairs(DRIVE_MASS) do copyFlat(dm, tDM, p, mr) end
    for _, p in ipairs(SUSP_COPY) do
        copyFlat(fr, tFront, p)
        copyFlat(rr, tRear, p)
    end
    for _, p in ipairs(SUSP_MASS) do
        copyFlat(fr, tFront, p, mr)
        copyFlat(rr, tRear, p, mr)
    end

    for _, t in ipairs(c.targets) do
        if get(t .. ".vehEngineData") ~= nil then
            TweakDB:SetFlat(t .. ".vehEngineData", eng)
            TweakDB:SetFlat(t .. ".vehDriveModelData", dm)
        else
            note("SCALED %s: variant %s not found, skipped", c.name, t)
        end
    end

    note("SCALED %s <- %s: torque %.0f -> %.0f (x%.3f), gear speed x%.3f, mass ratio %.3f, %d gears",
        c.name, T, tTorque, tTorque * r, r, vs, mr, n)
    return true
end

-- ------------------------------------------------------------------ BIKES pass
local BIKE_SLIP_GRIP_FLOOR = 0.73          -- burnOut.minLongFrictionCoeff floor (CVOO's bike value), see applyBike

local function applyBike(c)
    local main = c.targets[1]
    local ownEng, ownDM = get(main .. ".vehEngineData"), get(main .. ".bikeDriveModelData")
    if ownEng == nil or ownDM == nil then
        note("BIKES %s: record %s not found (mod not installed?), skipped", c.name, main)
        return false
    end
    local pre = main .. "_ccv"
    local eng, dm = pre .. "_engine", pre .. "_bdm"
    TweakDB:CloneRecord(eng, ownEng)
    TweakDB:CloneRecord(dm, ownDM)

    local oldT = get(eng .. ".engineMaxTorque")
    if c.torque then TweakDB:SetFlat(eng .. ".engineMaxTorque", c.torque) end

    local ownGears = get(eng .. ".gears")
    local names = {}
    local topOld, topNew = 0, 0
    if c.gears then
        -- explicit table: gear 0 = clone of the bike's own gear 0; gears 1..n = clones of its first forward gear, then set
        for gi = 2, #ownGears do                        -- 1.2.5: old top gear for the log line
            local okT, hiT = pcall(function() return TweakDB:GetFlat(TweakDBID.new(ownGears[gi], ".maxSpeed")) end)
            if okT and type(hiT) == "number" and hiT > topOld then topOld = hiT end
        end
        TweakDB:CloneRecord(pre .. "_gear0", ownGears[1])
        names[1] = pre .. "_gear0"
        for _, g in ipairs(c.gears) do
            local nm = pre .. "_gear" .. g.i
            TweakDB:CloneRecord(nm, ownGears[2] or ownGears[1])
            TweakDB:SetFlat(nm .. ".minSpeed", g.minSpeed)
            TweakDB:SetFlat(nm .. ".maxSpeed", g.maxSpeed)
            TweakDB:SetFlat(nm .. ".torqueMultiplier", g.tm)
            if g.minRPM then TweakDB:SetFlat(nm .. ".minEngineRPM", g.minRPM) end
            if g.maxRPM then TweakDB:SetFlat(nm .. ".maxEngineRPM", g.maxRPM) end
            names[#names + 1] = nm
            if g.maxSpeed > topNew then topNew = g.maxSpeed end
        end
        ownGears = {}                                   -- skip the scaling loop below
    end
    for i, gid in ipairs(ownGears) do
        local g = pre .. "_gear" .. (i - 1)
        TweakDB:CloneRecord(g, gid)
        names[#names + 1] = g
        if i > 1 and c.speedScale then                  -- index 1 is gear 0 (reverse / launch), left as is
            local lo, hi = get(g .. ".minSpeed"), get(g .. ".maxSpeed")
            if lo ~= nil then TweakDB:SetFlat(g .. ".minSpeed", lo * c.speedScale) end
            if hi ~= nil then
                if hi > topOld then topOld = hi end
                TweakDB:SetFlat(g .. ".maxSpeed", hi * c.speedScale)
                if hi * c.speedScale > topNew then topNew = hi * c.speedScale end
            end
        end
    end
    TweakDB:SetFlat(eng .. ".gears", names)

    local oldM = get(dm .. ".total_mass")
    if c.mass then
        TweakDB:SetFlat(dm .. ".total_mass", c.mass)
        TweakDB:SetFlat(dm .. ".chassis_mass", c.mass)
    end
    if c.drag then TweakDB:SetFlat(dm .. ".airResistanceFactor", c.drag) end
    -- 1.2.1: own wheel setup + rear preset, so the BIKE GRIP pass can raise this bike's rear grip without touching the author's
    -- records (shared by the colour variants and possibly by other bikes)
    local ownWs = get(dm .. ".wheelSetup")
    local ownRear = ownWs and get(ownWs .. ".backPreset")
    if ownWs ~= nil and ownRear ~= nil then
        TweakDB:CloneRecord(pre .. "_ws", ownWs)
        TweakDB:CloneRecord(pre .. "_rear", ownRear)
        TweakDB:SetFlat(pre .. "_ws.backPreset", pre .. "_rear")
        TweakDB:SetFlat(dm .. ".wheelSetup", pre .. "_ws")
    end
    -- 1.2.2: own burnOut record with the slipping-tyre grip floor raised. The Arch V4 bikes (all but the FZR) set
    -- minLongFrictionCoeff 0.1 (CVOO's bikes 0.73, vanilla 2w 0.4): once the rear slips (an upshift kick) it keeps 10 % grip,
    -- cannot hook up again and spins on the limiter (bench 03:21: Valor rpm at the limiter from 210 km/h in 6th, rpm running
    -- away from the gear band from 2nd gear on; V: screech at top speed). Launch grip bonus etc. stay the author's.
    local ownBo = get(dm .. ".burnOut")
    if ownBo ~= nil and TweakDB:GetRecord(ownBo) ~= nil then
        TweakDB:CloneRecord(pre .. "_burnout", ownBo)
        TweakDB:SetFlat(dm .. ".burnOut", pre .. "_burnout")
        local floor = get(pre .. "_burnout.minLongFrictionCoeff")
        if type(floor) == "number" and floor < BIKE_SLIP_GRIP_FLOOR then
            TweakDB:SetFlat(pre .. "_burnout.minLongFrictionCoeff", BIKE_SLIP_GRIP_FLOOR)
        end
    end

    local n = 0
    for _, t in ipairs(c.targets) do
        if get(t .. ".vehEngineData") ~= nil then
            TweakDB:SetFlat(t .. ".vehEngineData", eng)
            TweakDB:SetFlat(t .. ".bikeDriveModelData", dm)
            n = n + 1
        end
    end
    note("BIKES %s: torque %s -> %s, mass %s -> %s, drag %s, top gear %.1f -> %.1f m/s, %d records",
        c.name, tostring(oldT), tostring(c.torque), tostring(oldM), tostring(c.mass), tostring(c.drag), topOld, topNew, n)
    return true
end

-- ------------------------------------------------------------------ REALISM pass
-- Record name of a TweakDBID (CET knows the names of vanilla records and of CloneRecord clones), nil if unknown.
local function idName(id)
    if id == nil then return nil end
    if type(id) == "string" then return id end
    local ok, s = pcall(function() return TDBID.ToStringDEBUG(id) end)
    if ok and type(s) == "string" and s ~= "" and not s:find("^<") then return s end
    return nil
end

-- The engine / drive model the row's CVOO records are. Some CVOO modules (Kusanagi) tune the vanilla records in place
-- instead of cloning "<vehicle>_full_*": then they are resolved through the vehicle record (TweakDBID .. ".flat" works).
local function resolveRow(e)
    if get(e.engine .. ".engineMaxTorque") ~= nil then
        return e.engine, e.driveModel
    end
    local veh = e.engine:gsub("_full_enginedata$", "")
    local engId = get(veh .. ".vehEngineData")
    if engId == nil or get(engId .. ".engineMaxTorque") == nil then return nil, nil end
    return engId, get(veh .. ".bikeDriveModelData") or get(veh .. ".vehDriveModelData")
end

-- LIVE (1.2.0): other mods repoint vehicles away from CVOO's records. Authentic Shift deep-clones every ownable
-- vehicle's engine / gears / drive model to "AuthenticShift.<vehicle>_*_tuned" after CVOO ran and tunes the clones,
-- so CVOO's records (and this pass's values on them) only reached police and traffic. For each vehicle CVOO assigned to
-- this row (e.vehicles, generated), a live engine that is not the row's own record gets the row's torque, the row's
-- gear list (CVOO's gear records, already set above, are shared) and drag on its live drive model. Only records outside
-- the "Vehicle." namespace (another mod's clones) are written, so a shared vanilla or CVOO record is never touched.
-- Mass, brakes, steering, sound swaps of the other mod stay as they are. Idempotent: run at apply time and once more
-- after every mod's onInit (first frame with a player), whatever order CET loaded the mods in.
local function rewireLive(e, eng)
    local engName = idName(eng)
    local gearIds = get(eng .. ".gears")
    if engName == nil or type(gearIds) ~= "table" or #gearIds == 0 then return 0, 0, 0 end
    local gears = {}
    for i, gid in ipairs(gearIds) do gears[i] = idName(gid) or gid end
    local recs, n, unknown = {}, 0, 0
    for _, v in ipairs(e.vehicles or {}) do
        local live = get(v .. ".vehEngineData")
        local nm = idName(live)
        if live ~= nil and nm == nil then
            unknown = unknown + 1
        elseif nm ~= nil and nm ~= engName and not nm:find("^Vehicle%.") then
            if not recs[nm] then
                TweakDB:SetFlat(nm .. ".engineMaxTorque", e.torque)
                TweakDB:SetFlat(nm .. ".gears", gears)
                recs[nm] = true
            end
            local dm = get(v .. ".bikeDriveModelData")
            if dm == nil or TweakDB:GetRecord(dm) == nil then dm = get(v .. ".vehDriveModelData") end
            local dmName = idName(dm)
            if e.drag and dmName and not dmName:find("^Vehicle%.") and get(dmName .. ".airResistanceFactor") ~= nil then
                TweakDB:SetFlat(dmName .. ".airResistanceFactor", e.drag)
            end
            n = n + 1
        end
    end
    local nr = 0
    for _ in pairs(recs) do nr = nr + 1 end
    return n, nr, unknown
end

local function applyRealism(e)
    local eng, dm = resolveRow(e)
    if eng == nil then return false, "engine record missing" end
    local oldT = get(eng .. ".engineMaxTorque")
    if eng ~= e.engine then
        e = { name = e.name, engine = eng, gearPrefix = e.gearPrefix, torque = e.torque, drag = e.drag, gears = e.gears, target = e.target,
              driveModel = dm, vehicles = e.vehicles }
    end
    TweakDB:SetFlat(e.engine .. ".engineMaxTorque", e.torque)
    local n, top = 0, 0
    for _, g in ipairs(e.gears) do
        local rec = e.gearPrefix .. g.i
        if get(rec .. ".maxSpeed") ~= nil then
            TweakDB:SetFlat(rec .. ".minSpeed", g.minSpeed)
            TweakDB:SetFlat(rec .. ".maxSpeed", g.maxSpeed)
            TweakDB:SetFlat(rec .. ".torqueMultiplier", g.tm)
            n = n + 1
            if g.maxSpeed > top then top = g.maxSpeed end
        end
    end
    local oldD
    if e.driveModel and e.drag then
        oldD = get(e.driveModel .. ".airResistanceFactor")
        if oldD ~= nil then TweakDB:SetFlat(e.driveModel .. ".airResistanceFactor", e.drag) end
    end
    local okL, lv, lr, lu = pcall(rewireLive, e, e.engine)
    local live
    if okL then
        live = string.format("live: %d vehicles on %d foreign records%s", lv, lr, lu > 0 and string.format(", %d unnamed skipped", lu) or "")
        state.liveVehicles = (state.liveVehicles or 0) + lv
    else
        live = "live rewire failed: " .. tostring(lv)
    end
    return true, string.format("torque %.0f -> %.0f, %d/%d gears, top %.0f km/h, drag %s -> %.3f (%s) | %s",
        oldT, e.torque, n, #e.gears, top * 3.6, oldD and string.format("%.2f", oldD) or "-", e.drag or 0, e.target or "", live)
end

local function applyRealismAll()
    local ok, skipped = 0, 0
    state.liveVehicles = 0
    for _, e in ipairs(REALISM) do
        local fine, okRun, msg = pcall(applyRealism, e)
        if fine and okRun then
            ok = ok + 1
            log("REALISM %s: %s", e.name, msg)
        else
            skipped = skipped + 1
            note("REALISM %s: skipped (%s)", e.name, tostring(fine and msg or okRun))
        end
    end
    note("REALISM: %d vehicles set to their real-world acceleration / top speed, %d skipped; %d vehicles on other mods' records (Authentic Shift) rewired%s",
        ok, skipped, state.liveVehicles, RD.loadError and (" (realism_data.lua failed to load: " .. RD.loadError .. ")") or "")
end

-- Second LIVE pass, once, on the first frame with a player: every mod's onInit is done by then, so a mod that cloned
-- vehicles after this one (load order) gets the realism values written over its own tune as well.
local function rewireAllAgain()
    local total, recsTotal, failed = 0, 0, 0
    for _, e in ipairs(REALISM) do
        local okR, eng = pcall(resolveRow, e)
        if okR and eng ~= nil then
            local okL, lv, lr = pcall(rewireLive, e, eng)
            if okL then
                total = total + lv
                recsTotal = recsTotal + lr
            else
                failed = failed + 1
            end
        end
    end
    note("LIVE (after load): %d vehicles on %d foreign records hold the realism values%s", total, recsTotal,
        failed > 0 and string.format(", %d rows failed", failed) or "")
end

-- ------------------------------------------------------------------ BIKE GRIP (1.2.1)
-- Why: CVOO sets every bike's forwardWeightTransferFactor to 0.01 (default 1), so the rear tyre never gains load under
-- acceleration as a real bike's does (~all of the weight at 1 g), and Surface Type Expansion lowers bike asphalt grip
-- (long 1.0 -> 0.9). The realistic launch / post-shift force (~10 m/s2) then exceeds the rear grip: the rear wheel spins up
-- to the limiter at launch and after each upshift (bench 03:02: Tyger rpm 6300 at 50 km/h in 1st; V: "wheels breaking").
-- What: each bike's LIVE rear wheel preset (Authentic Shift's clone, CVOO's "_full_vehWheelSetupRearPreset" or this mod's
-- Arch V4 "_ccv_rear") gets frictionMulLongitudinal x BIKE_REAR_GRIP. Lateral grip, front tyre, weight transfer: unchanged.
-- Console: GetMod("CyberslopCustomVehicles").bikeGrip(1.8) sets another factor for the session (re-summon the bike).
-- 1.2.2: x1.6 -> x1.8 (bench 03:21: launch clean, a short chirp left right after each upshift).
-- QUICKSHIFT (1.2.2): at each upshift the engine free-revs during gearChangeTime (Tyger 5656 -> 6292 rpm, Valor 8632 ->
-- 9679) and the clutch then engages with that mismatch: a torque kick that chirps the rear tyre. Superbikes (Arch / Nazare,
-- Kusanagi, Arch V4) get gearChangeTime BIKE_SHIFT_TIME (real quickshifter ~0.05 s, CVOO 0.12-0.2, Arch V4 0.15) on their
-- live engine; never raised, Apollo (no quickshifter) left alone. Console: GetMod("CyberslopCustomVehicles").bikeShift(0.05)
local BIKE_REAR_GRIP = 1.8
local BIKE_SHIFT_TIME = 0.05          -- 1.2.3: 0.08 -> 0.05 (V tried 0.05 at 04:29: no rpm flare left at any upshift)
local gripBase = {}                        -- rear preset name -> its value before this mod
local gripWritten = {}                     -- values this mod wrote (a later clone of a boosted preset is not boosted twice)
local shiftBase = {}                       -- engine name -> its gearChangeTime before this mod

local function gripAllowed(name)
    return name ~= nil and (not name:find("^Vehicle%.") or name:find("_full_vehWheelSetupRearPreset$") ~= nil
        or name:find("_ccv_rear$") ~= nil)
end

local function engineAllowed(name)
    return name ~= nil and (not name:find("^Vehicle%.") or name:find("_full_enginedata$") ~= nil
        or name:find("_ccv_engine$") ~= nil)
end

local function setShift(eng)
    TweakDB:SetFlat(eng .. ".gearChangeTime", math.min(shiftBase[eng], BIKE_SHIFT_TIME))
end

local function rearPresetOf(v)
    local dm = get(v .. ".bikeDriveModelData")
    if dm == nil or TweakDB:GetRecord(dm) == nil then return nil end
    local ws = get(dm .. ".wheelSetup")
    if ws == nil then return nil end
    return idName(get(ws .. ".backPreset"))
end

local function setGrip(rr)
    local v = gripBase[rr] * BIKE_REAR_GRIP
    TweakDB:SetFlat(rr .. ".frictionMulLongitudinal", v)
    gripWritten[string.format("%.5f", v)] = gripBase[rr]
end

local function applyBikeGrip()
    local n, skipped, seen, q, seenE = 0, 0, {}, 0, {}
    local function one(v, quick)
        local ok, rr = pcall(rearPresetOf, v)
        if not ok or rr == nil then return end            -- not a bike (or not installed)
        if quick then
            local eng = idName(get(v .. ".vehEngineData"))
            if eng ~= nil and not seenE[eng] and engineAllowed(eng) then
                seenE[eng] = true
                if shiftBase[eng] == nil then
                    local cur = get(eng .. ".gearChangeTime")
                    if type(cur) == "number" then shiftBase[eng] = cur end
                end
                if shiftBase[eng] ~= nil then setShift(eng); q = q + 1 end
            end
        end
        if seen[rr] then return end
        seen[rr] = true
        if not gripAllowed(rr) then skipped = skipped + 1; return end
        if gripBase[rr] == nil then
            local cur = get(rr .. ".frictionMulLongitudinal")
            if type(cur) ~= "number" then return end
            gripBase[rr] = gripWritten[string.format("%.5f", cur)] or cur
        end
        setGrip(rr)
        n = n + 1
    end
    for _, e in ipairs(REALISM) do
        local quick = not tostring(e.name):lower():find("apollo")
        for _, v in ipairs(e.vehicles or {}) do one(v, quick) end
    end
    for _, c in ipairs(BIKES) do for _, t in ipairs(c.targets or {}) do one(t, true) end end
    return n, skipped, q
end

function M.bikeShift(t)
    if type(t) == "number" and t > 0 then BIKE_SHIFT_TIME = t end
    local n = 0
    for eng in pairs(shiftBase) do setShift(eng); n = n + 1 end
    print(string.format("[CyberslopCustomVehicles] superbike gear change %.2f s on %d engines: dismiss and re-summon the bike", BIKE_SHIFT_TIME, n))
    log("QUICKSHIFT: console set %.2f s on %d engines", BIKE_SHIFT_TIME, n)
end

function M.bikeGrip(f)
    if type(f) == "number" and f > 0 then BIKE_REAR_GRIP = f end
    local n = 0
    for rr in pairs(gripBase) do setGrip(rr); n = n + 1 end
    print(string.format("[CyberslopCustomVehicles] bike rear grip x%.2f on %d rear presets: dismiss and re-summon the bike", BIKE_REAR_GRIP, n))
    log("BIKE GRIP: console set x%.2f on %d rear presets", BIKE_REAR_GRIP, n)
end

local function bikeGripPass(label)
    local ok, n, skipped, q = pcall(applyBikeGrip)
    if ok then
        note("BIKE GRIP (%s): rear longitudinal grip x%.2f on %d bike rear presets%s; quickshift %.2f s on %d superbike engines",
            label, BIKE_REAR_GRIP, n, skipped > 0 and string.format(", %d shared vanilla presets left alone", skipped) or "",
            BIKE_SHIFT_TIME, q)
    else
        note("BIKE GRIP (%s) failed: %s", label, tostring(n))
    end
end

-- ------------------------------------------------------------------ driver
local function apply(reason)
    if get(MARK) ~= nil then
        note("already applied in this session (CET reload), nothing to do (%s)", reason)
        state.applied = true
        state.reloaded = true                          -- 1.2.4: bike grip already boosted in the TweakDB
        return true
    end
    if get(CVOO_MARK) == nil then
        return false                                   -- CVOO has not run yet
    end
    note("Cyberslop Custom Vehicles %s: CVOO marker found, applying (%s)", VERSION, reason)
    local ok, err = pcall(applyClones)
    if not ok then note("CLONES pass failed: %s", tostring(err)) end
    for _, c in ipairs(SCALED) do
        local ok2, res = pcall(applyScaled, c)
        if not ok2 then note("SCALED %s failed: %s", c.name, tostring(res)) end
    end
    for _, c in ipairs(BIKES) do
        local ok3, res = pcall(applyBike, c)
        if not ok3 then note("BIKES %s failed: %s", c.name, tostring(res)) end
    end
    local ok4, err4 = pcall(applyRealismAll)              -- last: overrides CVOO's and the SCALED pass's drivetrain numbers
    if not ok4 then note("REALISM pass failed: %s", tostring(err4)) end
    bikeGripPass("load")
    TweakDB:SetFlat(MARK, true)
    state.applied = true
    return true
end

function M.status()
    print(string.format("[CyberslopCustomVehicles %s] applied=%s gaveUp=%s", VERSION, tostring(state.applied), tostring(state.gaveUp)))
    for _, line in ipairs(state.report) do print("  " .. line) end
end

registerForEvent("onInit", function()
    state.tried = true
    if not apply("onInit") then
        log("CVOO marker not set yet at onInit, waiting for it (up to %d s)", GIVE_UP_SECONDS)
    end
end)

registerForEvent("onUpdate", function(dt)
    if state.applied and not state.liveAgain then
        if Game.GetPlayer() == nil then return end
        -- 1.2.5: the player object exists at the main menu already; wait until a save is really loaded
        local okPG, pre = pcall(function() return Game.GetSystemRequestsHandler():IsPreGame() end)
        if okPG and pre == true then return end
        state.liveAgain = true
        local ok, err = pcall(rewireAllAgain)
        if not ok then note("LIVE (after load) failed: %s", tostring(err)) end
        if state.reloaded then
            -- 1.2.4: after a CET reload the presets already hold base x BIKE_REAR_GRIP and gripBase is empty, so a
            -- pass would take the boosted value as the base and multiply it again (x3.24, x5.83, ...)
            note("BIKE GRIP (after load): skipped, CET reload (rear presets already boosted in this game session)")
        else
            bikeGripPass("after load")
        end
        return
    end
    if state.applied or state.gaveUp or not state.tried then return end
    state.elapsed = state.elapsed + dt
    state.timer = state.timer + dt
    if state.timer < 1.0 then return end
    state.timer = 0.0
    if apply("onUpdate after " .. string.format("%.0f", state.elapsed) .. " s") then return end
    if state.elapsed >= GIVE_UP_SECONDS then
        state.gaveUp = true
        note("gave up after %d s: Cyber Vehicle Overhaul never set %s (CVOO missing or disabled), nothing changed", GIVE_UP_SECONDS, CVOO_MARK)
    end
end)

return M
