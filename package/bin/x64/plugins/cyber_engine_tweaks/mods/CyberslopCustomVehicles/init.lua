-- ============================================================
--  Cyberslop Custom Vehicles 1.2.5 (2026-11-02; 1.2.4 + 1.2.5 2026-11-23)
--  1.2.5: the "LIVE (after load)" pass waits for a loaded save (not the main menu, where the player object already
--  exists), and the BIKES log line shows the bike's real old top gear (was always 0.0 with an explicit gear table).
--  1.2.4: a CET "Reload all mods" no longer multiplies the bike rear grip by 1.8 again (the TweakDB keeps the boosted
--  values across a reload while the Lua base table starts empty, so the grip pass is skipped after a reload).
--  Gives the custom vehicles the same handling tuning Cyber Vehicle Overhaul (CVOO) gives the vanilla cars, and
--  (1.1.0) sets every vehicle's acceleration and top speed to what its stated specs give in the real world.
-- ============================================================
-- Why: CVOO retunes vanilla vehicle records by name. A custom vehicle that is a TweakXL "$base" copy of a vanilla
-- record (NCPD Fleet, Fixernet van, Caliburn Legacy, Apollo Tactical, Methodd Edge) copied the vanilla physics at
-- TweakXL load, before CVOO ran, so it still drives like stock. Cars that bring their own engine and chassis
-- (NSX Liberty Walk, Supron Widebody, Merrimac Necromancer) have numbers that do not match CVOO's at all.
-- What:
--   CLONES: each target gets the already-tuned vehEngineData and vehDriveModelData (bikeDriveModelData for bikes)
--           of its vanilla base. Nothing is copied but those two pointers.
--   SCALED: the target's own records are cloned (ride height, wheel offsets, mass, centre of mass stay the author's)
--           and CVOO's template car supplies gearbox, RPM, drag, friction map, steering, brake and suspension
--           character. Torque is scaled by hp / hpRef, gear speeds by (hp / hpRef)^(1/3) (clamped), brake torque and
--           spring / damper rates by the mass ratio (same ride frequency and brake deceleration as the template).
--   BIKES:  (1.1.0) the Arch V4 bikes get their own records cloned and a new 6-gear table, torque, physics mass and drag
--           from realism_data.lua (gear 0 / reverse, brakes, suspension, tilt stay the author's).
--   REALISM: (1.1.0) every CVOO vehicle (cars and its bikes) and the three SCALED cars: engine torque, forward gear speed
--           bands and torque multipliers, and drag (airResistanceFactor) from realism_data.lua. Targets: the vehicle's own
--           stated hp / mass / drive layout -> real-world 0-100 km/h, 0-200 km/h and top speed, on the true speed scale.
--           Written to CVOO's own records, so CVOO's variants and the CLONES follow. realism_data.lua is generated by
--           scripts\realism_plan.py: re-run that, do not hand-edit it. Mass, brakes, steering, suspension: unchanged.
--   LIVE:   (1.2.0) the same values also go onto the records each vehicle really uses when another mod repointed it
--           (Authentic Shift clones every ownable vehicle after CVOO: without this the player's cars kept CVOO x Authentic
--           Shift values). See rewireLive. Game constants in realism_data.lua are now MEASURED in game (CyberslopVehicleBench).
-- Order: CVOO must have run first. CVOO sets the flat cyberVehicleOverhaul.hasUpgraded at the end of its onInit;
-- this mod applies once that flat exists (at its own onInit when CET loads it after CVOO, else within 120 s).
